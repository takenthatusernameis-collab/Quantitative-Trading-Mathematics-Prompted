"""Pin ``EXPERIMENT_LINEAGE_REPORT.md`` reproducibility.

``EXPERIMENT_LINEAGE_REPORT.md`` is generated by
``scripts/generate_experiment_lineage_report.py`` from
``.experiments/experiments.jsonl`` (173 records). Re-running the generator on
this checkout reproduces the committed file exactly except for the
``**Generated:**`` timestamp line, which is intentionally not pinned (it is a
wall-clock stamp, not a derived value).

This test closes the last unpinned generated inventory in the same drift
class as ``EXPERIMENT_ARTIFACT_AUDIT.md`` (see
``tests/test_experiment_artifact_schema.py``): a committed report that drifts
from the corpus it describes. It regenerates the report **in memory** (to a
temporary file) and asserts the non-timestamp content equals the committed
report, so the committed file is never rewritten as a side effect of the
test.

The category summary table and total-experiment count are pinned as well so
a silent corpus change (added/removed records, a verdict flip) is surfaced
deliberately rather than as a doc drift.

Read-only: does not modify ``src/qtr``, frozen-contract tests, or artifacts.
"""

from __future__ import annotations

import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMITTED_REPORT = ROOT / "EXPERIMENT_LINEAGE_REPORT.md"
GENERATOR = ROOT / "scripts" / "generate_experiment_lineage_report.py"

# The only line that is not reproducible is the wall-clock generation stamp.
TIMESTAMP_PREFIX = "**Generated:**"

# Pinned from the committed report (re-verified 2026-11-13 by regeneration).
EXPECTED_TOTAL_EXPERIMENTS = 173
EXPECTED_CATEGORY_SUMMARY = frozenset(
    {
        ("Baseline / MA Crossover", 9, 6, 0, 3),
        ("Time-Series Momentum", 60, 41, 0, 16),
        ("Cross-Sectional Momentum", 2, 2, 0, 0),
        ("Regime-Gated", 5, 5, 0, 0),
        ("Volatility / VRP", 9, 5, 2, 2),
        ("Volume Predictive", 6, 3, 0, 3),
        ("Hypothesis H10-H29", 23, 16, 0, 7),
        ("New Family (NF) - Recent", 51, 27, 14, 10),
        ("New Family (NF) - Factor/Other", 5, 4, 0, 1),
        ("Other / Uncategorized", 3, 2, 0, 1),
    }
)


def _strip_generated_line(text: str) -> str:
    """Remove the wall-clock ``**Generated:**`` line from a report."""
    return "\n".join(line for line in text.splitlines() if not line.startswith(TIMESTAMP_PREFIX))


def _regenerate_report() -> str:
    """Regenerate the lineage report to a temp file and return its contents."""
    if sys.path[0] != str(ROOT / "scripts"):
        sys.path.insert(0, str(ROOT / "scripts"))
    import generate_experiment_lineage_report as gen

    jsonl_path = ROOT / ".experiments" / "experiments.jsonl"
    with tempfile.TemporaryDirectory() as tmp:
        out_path = Path(tmp) / "EXPERIMENT_LINEAGE_REPORT.md"
        gen.generate_report(gen.load_experiments(jsonl_path), out_path)
        return out_path.read_text()


def test_committed_report_exists():
    assert COMMITTED_REPORT.is_file(), "EXPERIMENT_LINEAGE_REPORT.md is missing"


def test_generator_is_importable():
    assert GENERATOR.is_file(), "scripts/generate_experiment_lineage_report.py is missing"


def test_report_reproduces_committed_content():
    """Regenerated report matches the committed report except the timestamp."""
    assert COMMITTED_REPORT.is_file()
    committed = _strip_generated_line(COMMITTED_REPORT.read_text())
    regenerated = _strip_generated_line(_regenerate_report())
    assert regenerated == committed, (
        "EXPERIMENT_LINEAGE_REPORT.md no longer reproduces from "
        ".experiments/experiments.jsonl; regenerate the report deliberately "
        "and update this pin."
    )


def test_report_total_experiment_count():
    """The report's declared total matches the pinned corpus size."""
    text = COMMITTED_REPORT.read_text()
    assert f"**Total Experiments:** {EXPECTED_TOTAL_EXPERIMENTS}" in text, (
        f"expected **Total Experiments:** {EXPECTED_TOTAL_EXPERIMENTS}"
    )


def test_report_category_summary_matches_pinned_inventory():
    """The summary-by-category table matches the pinned inventory."""
    text = COMMITTED_REPORT.read_text()
    for category, count, passed, failed, errors in EXPECTED_CATEGORY_SUMMARY:
        row = f"| {category} | {count} | {passed} | {failed} | {errors} |"
        assert row in text, f"missing/changed category row: {row}"
